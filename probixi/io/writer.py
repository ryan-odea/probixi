from __future__ import annotations

import math
import re
from bisect import bisect_right
from pathlib import Path
from typing import TYPE_CHECKING, Optional, Union

import torch

from ..indexer.forward import detector_to_q
from ..indexer.lattice import B_to_cell
from .geometry import EV_ANGSTROM

if TYPE_CHECKING:
    from ..indexer.indexer import IndexResult
    from .cell import CellParams

PathLike = Union[str, Path]

STREAM_VERSION = "CrystFEL stream format 2.3"
A_INV_TO_NM_INV = 10.0  # 1 A^-1 = 10 nm^-1
A_TO_NM = 0.1  # 1 A = 0.1 nm
DEFAULT_PROFILE_RADIUS_NM_INV = 0.002
PROFILE_RADIUS_RMSD_FACTOR = 0.6
PROFILE_RADIUS_MIN_NM_INV = 0.0005
PROFILE_RADIUS_MAX_NM_INV = 0.020
_BARE_WAVELENGTH = re.compile(r"^(\s*wavelength\s*=\s*)([-+.\deE]+)(\s*(;.*)?)$")
_ENERGY_LINE = re.compile(r"^\s*(photon_energy|electron_voltage)\s*=")
_CLEN_LINE = re.compile(r"^(\s*clen\s*=\s*)([-+.\deE]+)", re.M)


def _crystfel_geometry(text: str) -> str:
    # A bare wavelength, read as Å, gains its unit; energy lines are commented out
    lines = text.split("\n")
    if not any(_BARE_WAVELENGTH.match(line) for line in lines):
        return text
    return "\n".join(
        (
            _BARE_WAVELENGTH.sub(r"\1\2 A\3", line)
            if _BARE_WAVELENGTH.match(line)
            else ";" + line if _ENERGY_LINE.match(line) else line
        )
        for line in lines
    )


def _profile_radius_nm_inv(rmsd_a_inv: float) -> float:
    if not math.isfinite(rmsd_a_inv) or rmsd_a_inv <= 0.0:
        return DEFAULT_PROFILE_RADIUS_NM_INV
    r = PROFILE_RADIUS_RMSD_FACTOR * rmsd_a_inv * A_INV_TO_NM_INV
    return min(max(r, PROFILE_RADIUS_MIN_NM_INV), PROFILE_RADIUS_MAX_NM_INV)


def _reflection_flags(result) -> tuple:
    # (n_pixels_total, n_masked, n_overlap) lists, zeros if unrecorded; () if none
    cols = (
        result.predicted_n_pixels_total,
        result.predicted_n_masked,
        result.predicted_n_overlap,
    )
    if all(c is None for c in cols):
        return ()
    n = len(result.predicted_hkl)
    return tuple([0] * n if c is None else c.detach().cpu().tolist() for c in cols)


def _profile_radius(result) -> float:
    r = getattr(result, "profile_radius", None)
    if r is not None and math.isfinite(r) and r > 0.0:
        r_nm = r * A_INV_TO_NM_INV
        return min(max(r_nm, PROFILE_RADIUS_MIN_NM_INV), PROFILE_RADIUS_MAX_NM_INV)
    return _profile_radius_nm_inv(result.rmsd)


class _StreamWriter:
    # Frame location, per-event geometry and .stream formatting, shared with the DB

    def __init__(
        self,
        path: PathLike,
        geometry: dict,
        *,
        geometry_file: Optional[PathLike] = None,
        files: Optional[dict] = None,
        indexer_name: str = "probixi",
        panel: str = "0",
        integration: Optional[dict] = None,
    ):
        self.path = Path(path)
        self.geometry = geometry
        self.indexer_name = indexer_name
        self.integration = integration
        self.panel = panel
        self._panels = _panel_bounds(geometry.get("panels"))
        self._geometry_file = Path(geometry_file) if geometry_file else None
        self._ranges = _build_frame_ranges(files)
        self._range_starts = [r[0] for r in self._ranges]
        self._event_starts = [
            getattr(info, "event_start", 0) for info in (files or {}).values()
        ]
        self._eventless = {
            str(info.filename)
            for info in (files or {}).values()
            if getattr(info, "eventless", False)
        }
        self._event_names = {
            str(info.filename): info.events
            for info in (files or {}).values()
            if getattr(info, "events", None) is not None
        }
        self._energies = {
            str(info.filename): info.photon_energy_eV
            for info in (files or {}).values()
            if getattr(info, "photon_energy_eV", None) is not None
        }
        self._fh = None
        self._serial = 0

    def __enter__(self) -> "_StreamWriter":
        self._fh = self.path.open("w")
        self._write_header()
        return self

    def __exit__(self, *exc) -> None:
        if self._fh is not None:
            self._fh.close()
            self._fh = None

    def __call__(self, result) -> None:
        self.write(result)

    def write(self, result) -> None:
        raise NotImplementedError

    def _write_header(self) -> None:
        assert self._fh is not None
        lines = [STREAM_VERSION, f"Generated by {self.indexer_name}"]
        if self.integration and self.integration.get("radii"):
            radii = ",".join(f"{float(r):g}" for r in self.integration["radii"])
            lines.append(f"indexamajig --integration=rings-cen --int-radius={radii}")
        if self._geometry_file and self._geometry_file.is_file():
            lines.append("----- Begin geometry file -----")
            lines.append(_crystfel_geometry(self._geometry_text().rstrip("\n")))
            lines.append("----- End geometry file -----")
        self._fh.write("\n".join(lines) + "\n")

    def _peak_search_lines(
        self,
        frame_index: Optional[int],
        positions,
        intensities,
        num_peaks: int,
        indexed_by: str,
    ) -> list[str]:
        filename, event = self._locate(frame_index)
        g = self._frame_geometry(filename, event)
        photon_eV = EV_ANGSTROM / float(g["wavelength"])
        names = self._event_names.get(filename)
        if names is not None:
            event_line = f"Event: {names[event]}//"
        else:
            event_line = f"Event: //{'' if filename in self._eventless else event}"

        peak_rows: list[str] = []
        recips = self._resolution_nm_inv_many(positions, g)
        max_recip = max(recips, default=0.0)
        for (row, col), intensity, recip in zip(positions, intensities, recips):
            # fs = column (fast scan), ss = row (slow scan)
            peak_rows.append(
                f"{col:7.2f} {row:7.2f} {recip:10.2f} {intensity:10.2f}   "
                f"{self._panel_for(col, row)}"
            )

        return [
            "----- Begin chunk -----",
            f"Image filename: {filename}",
            event_line,
            f"Image serial number: {self._serial}",
            "hit = 1",  # placeholder; DataOffloader sets it from the peak count
            f"indexed_by = {indexed_by}",
            "n_indexing_tries = 1",
            f"photon_energy_eV = {photon_eV:.2f}",
            # divergence/bandwidth not modelled; CrystFEL defaults
            "beam_divergence = 0.00e+00 rad",
            "beam_bandwidth = 1.00e-08 (fraction)",
            f"average_camera_length = {float(g['clen']):.6f} m",
            f"num_peaks = {num_peaks}",
            "num_saturated_peaks = 0",
            f"peak_resolution = {_resolution_line(max_recip)}",
            "Peaks from peak search",
            "  fs/px   ss/px (1/d)/nm^-1   Intensity  Panel",
            *peak_rows,
            "End of peak list",
        ]

    def _geometry_text(self) -> str:
        # geometry file text, clen moved by the camera-length fit
        text = self._geometry_file.read_text()
        shift = self.geometry.get("clen_shift")
        if not shift:
            return text
        return _CLEN_LINE.sub(
            lambda m: f"{m.group(1)}{float(m.group(2)) + shift:.6f}", text, count=1
        )

    def _frame_geometry(self, filename: str, event: int) -> dict:
        # A per-event photon energy overrides the run wavelength
        e = self._energies.get(filename)
        if e is None or not 0 <= event < len(e) or not e[event] > 0:
            return self.geometry
        return {**self.geometry, "wavelength": EV_ANGSTROM / float(e[event])}

    def _resolution_nm_inv_many(self, positions, geometry=None) -> list[float]:
        pos = [(float(row), float(col)) for row, col in positions]
        if not pos:
            return []
        q = detector_to_q(
            torch.tensor(pos, dtype=torch.float32),
            geometry or self.geometry,
            dtype=torch.float32,
        )
        return (torch.linalg.vector_norm(q, dim=-1) * A_INV_TO_NM_INV).tolist()

    def _resolution_nm_inv(self, row: float, col: float) -> float:
        return self._resolution_nm_inv_many([(row, col)])[0]

    def _panel_for(self, fs: float, ss: float) -> str:
        # Panel containing (fs, ss), else the fallback name
        for name, min_fs, max_fs, min_ss, max_ss in self._panels:
            if min_fs <= fs <= max_fs and min_ss <= ss <= max_ss:
                return name
        return self.panel

    def _locate(self, frame_index: Optional[int]) -> tuple[str, int]:
        if frame_index is None:
            return "unknown", 0
        i = bisect_right(self._range_starts, frame_index) - 1
        if i >= 0:
            start, stop, fname = self._ranges[i]
            if frame_index < stop:
                return fname, frame_index - start + self._event_starts[i]
        return "unknown", int(frame_index)


class DataOffloader(_StreamWriter):
    """Write index results to a CrystFEL ``.stream`` file.

    The stream carries only what CrystFEL reads. Reflections whose signal disk
    touches the mask, the frame edge or another predicted disk are left out, as
    are peaks bordering the mask; :class:`DuckDBOffloader` keeps them, with the
    model background under each disk, pixel counts and per-crystal diagnostics.
    The stream output may be deprecated in favour of the database.

    Parameters
    ----------
    path : str or Path
        Destination stream file.
    geometry : dict
        Indexer geometry: ``beam_center``, ``clen``, ``pixel_size``,
        ``wavelength`` and, when available, the parsed ``panels``.
    cell : CellParams, optional
        Target cell, the source of ``lattice_type``, ``centering`` and
        ``unique_axis``. Each crystal's cell comes from its orientation matrix.
    geometry_file : str or Path, optional
        Geometry file embedded in the header, with ``clen`` moved by any
        camera-length fit.
    files : dict, optional
        Loader file map, which resolves frame indices to file and event.
    indexer_name : str, default "probixi"
        Value of the ``Generated by`` line. Each chunk's ``indexed_by`` is
        ``fromfile``, a method name CrystFEL recognises.
    panel : str, default "0"
        Panel name for peaks outside every geometry panel, or for a geometry
        without panels.
    integration : dict, optional
        Integration recipe, as :attr:`~probixi.Probixi.integration_recipe`
        returns it. Its ``radii`` go into the header as an
        ``indexamajig --int-radius`` line.

    Notes
    -----
    Use as a context manager. The instance is callable, so it can be passed to
    ``IndexStream.to_stream``::

        with DataOffloader(out, geometry=geom, cell=cell, files=files) as off:
            stream.to_stream(off)
    """

    def __init__(
        self,
        path: PathLike,
        geometry: dict,
        *,
        cell: Optional["CellParams"] = None,
        geometry_file: Optional[PathLike] = None,
        files: Optional[dict] = None,
        indexer_name: str = "probixi",
        panel: str = "0",
        integration: Optional[dict] = None,
    ):
        super().__init__(
            path,
            geometry,
            geometry_file=geometry_file,
            files=files,
            indexer_name=indexer_name,
            panel=panel,
            integration=integration,
        )
        self.cell = cell

    def write(self, result: "IndexResult") -> None:
        """Append one frame and its lattices as a CrystFEL chunk."""
        if self._fh is None:
            raise RuntimeError("DataOffloader must be used as a context manager")
        self._serial += 1
        self._fh.write(self._format_chunk(result))

    def _format_chunk(self, result: "IndexResult") -> str:
        crystals = getattr(result, "crystals", [result])
        positions = result.positions.detach().cpu().tolist()
        intensities = result.intensities.detach().cpu().tolist()
        if result.peak_n_masked is not None:  # peaks bordering the mask stay out
            clean = [m == 0 for m in result.peak_n_masked.detach().cpu().tolist()]
            positions = [p for p, c in zip(positions, clean) if c]
            intensities = [i for i, c in zip(intensities, clean) if c]
        out = self._peak_search_lines(
            result.frame_index,
            positions,
            intensities,
            len(positions),
            "fromfile" if crystals else "none",
        )
        # A hit has the MIN_PEAKS_TO_INDEX (5) peaks indexing needs
        out[out.index("hit = 1")] = f"hit = {int(result.n_peaks >= 5)}"
        for crystal in crystals:
            out += self._format_crystal(
                crystal,
                crystal.A.detach().cpu().tolist(),
                crystal.hkl.detach().cpu().tolist(),
                crystal.indexed_mask.detach().cpu().tolist(),
                crystal.positions.detach().cpu().tolist(),
                crystal.intensities.detach().cpu().tolist(),
                crystal.sigmas.detach().cpu().tolist(),
            )
        out.append("----- End chunk -----")
        return "\n".join(out) + "\n"

    def _format_crystal(
        self,
        result: "IndexResult",
        A: list,
        hkl: list,
        indexed: list,
        positions: list,
        intensities: list,
        sigmas: list,
    ) -> list[str]:
        recovered = B_to_cell(result.A)
        cell = self.cell or result.cell
        a_nm = recovered.a * A_TO_NM
        b_nm = recovered.b * A_TO_NM
        c_nm = recovered.c * A_TO_NM
        al, be, ga = (
            math.degrees(recovered.alpha),
            math.degrees(recovered.beta),
            math.degrees(recovered.gamma),
        )
        # columns of A are reciprocal basis vectors a*/b*/c* (A^-1 -> nm^-1)
        astar = [A[r][0] * A_INV_TO_NM_INV for r in range(3)]
        bstar = [A[r][1] * A_INV_TO_NM_INV for r in range(3)]
        cstar = [A[r][2] * A_INV_TO_NM_INV for r in range(3)]

        # Predicted-and-integrated lattice when available, else observed peaks
        if result.predicted_hkl is not None:
            assert (
                result.predicted_positions is not None
                and result.predicted_intensities is not None
                and result.predicted_sigmas is not None
                and result.predicted_peak is not None
                and result.predicted_background is not None
            )
            p_pos = result.predicted_positions.detach().cpu().tolist()
            p_hkl = result.predicted_hkl.detach().cpu().tolist()
            p_int, p_sig, p_pk, p_bg = (
                torch.stack(
                    [
                        result.predicted_intensities,
                        result.predicted_sigmas,
                        result.predicted_peak,
                        result.predicted_background,
                    ]
                )
                .detach()
                .cpu()
                .tolist()
            )
            refl = list(zip(p_pos, p_hkl, p_int, p_sig, p_pk, p_bg))
            flags = _reflection_flags(result)
            if flags:  # disks touching the mask, the edge or another disk stay out
                refl = [
                    r for r, m, o in zip(refl, flags[1], flags[2]) if m == 0 and o == 0
                ]
        else:
            refl = [
                (rc, hk, i, s, 0.0, 0.0)
                for rc, hk, keep, i, s in zip(
                    positions, hkl, indexed, intensities, sigmas
                )
                if keep
            ]

        # sigma 0 marks a disk with no usable pixel
        refl = [r for r in refl if math.isfinite(r[3]) and r[3] > 0.0]

        max_recip = max(
            self._resolution_nm_inv_many(
                [rc for rc, *_ in refl],
                self._frame_geometry(*self._locate(result.frame_index)),
            ),
            default=0.0,
        )
        limit = result.diffraction_limit
        drl_recip = limit if (limit is not None and math.isfinite(limit)) else max_recip

        lines = [
            "--- Begin crystal",
            f"Cell parameters {a_nm:.5f} {b_nm:.5f} {c_nm:.5f} nm, "
            f"{al:.2f} {be:.2f} {ga:.2f} deg",
            "astar = {:+.7f} {:+.7f} {:+.7f} nm^-1".format(*astar),
            "bstar = {:+.7f} {:+.7f} {:+.7f} nm^-1".format(*bstar),
            "cstar = {:+.7f} {:+.7f} {:+.7f} nm^-1".format(*cstar),
            f"lattice_type = {cell.lattice_type or 'triclinic'}",
            f"centering = {cell.centering or 'P'}",
            f"unique_axis = {cell.unique_axis or '?'}",
            f"profile_radius = {_profile_radius(result):.5f} nm^-1",
            f"diffraction_resolution_limit = {_resolution_line(drl_recip)}",
            f"num_reflections = {len(refl)}",
            "num_saturated_reflections = 0",
            "num_implausible_reflections = 0",
            "Reflections measured after indexing",
            "   h    k    l          I   sigma(I)       peak background  "
            "fs/px  ss/px panel",
        ]
        for (
            (row, col),
            (h, k, l),  # noqa: E741
            intensity,
            sigma,
            peak,
            background,
        ) in refl:
            lines.append(
                f"{int(h):4d} {int(k):4d} {int(l):4d} {intensity:10.2f} "
                f"{sigma:10.2f} {peak:10.2f} {background:10.2f} "
                f"{col:6.1f} {row:6.1f} {self._panel_for(col, row)}"
            )
        lines += ["End of reflections", "--- End crystal"]
        return lines


def _resolution_line(recip_nm_inv: float) -> str:
    # CrystFEL "<X> nm^-1 or <Y> A" from 1/d in nm^-1 (d_A = 10 / recip)
    if recip_nm_inv <= 0.0:
        return "0.000000 nm^-1 or inf A"
    d_angstrom = 10.0 / recip_nm_inv
    return f"{recip_nm_inv:.6f} nm^-1 or {d_angstrom:.6f} A"


def _panel_bounds(
    panels: Optional[dict],
) -> list[tuple[str, int, int, int, int]]:
    # Flatten panels to (name, min_fs, max_fs, min_ss, max_ss)
    out: list[tuple[str, int, int, int, int]] = []
    if not panels:
        return out
    for name, data in panels.items():
        try:
            out.append(
                (
                    str(name),
                    int(data["min_fs"]),
                    int(data["max_fs"]),
                    int(data["min_ss"]),
                    int(data["max_ss"]),
                )
            )
        except (KeyError, TypeError, ValueError):
            continue
    return out


def _build_frame_ranges(files: Optional[dict]) -> list[tuple[int, int, str]]:
    # Cumulative (start, stop, filename) ranges over files in load order
    ranges: list[tuple[int, int, str]] = []
    if not files:
        return ranges
    start = 0
    for fname, info in files.items():
        n = int(getattr(info, "n_frames", 0))
        ranges.append((start, start + n, str(getattr(info, "filename", fname))))
        start += n
    return ranges
